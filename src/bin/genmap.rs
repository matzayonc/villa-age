//! Generates a map file from a seed: a village of villagers in the middle, trees scattered over
//! the rest with a clearing around the village, and rabbits everywhere. The same seed and
//! options always produce the same file, so the built-in map is regenerated rather than edited:
//!
//! ```text
//! cargo run --bin genmap -- --seed 1 --size 400
//! ```

use std::path::PathBuf;

use clap::Parser;
use rand::{RngExt, SeedableRng};
use rand_chacha::ChaCha8Rng;
use ron::ser::PrettyConfig;
use villa_age::map::{MapConfig, TUNING_AREA, TreeSpec};

/// Generate a map file.
#[derive(Parser)]
#[command(version, about)]
struct Cli {
    /// Seed for the layout; the same seed and options reproduce the same map.
    #[arg(long, default_value_t = 1)]
    seed: u64,
    /// Side length of the square map in world units.
    #[arg(long, default_value_t = 400.0)]
    size: f32,
    /// Number of villagers; by default as dense as the original 40×40 map (5).
    #[arg(long)]
    villagers: Option<usize>,
    /// Number of trees; by default as dense as the original 40×40 map (24).
    #[arg(long)]
    trees: Option<usize>,
    /// Number of rabbits; by default as dense as the original 40×40 map (6).
    #[arg(long)]
    rabbits: Option<usize>,
    /// Where to write the map.
    #[arg(long, default_value = "assets/maps/default.ron")]
    out: PathBuf,
}

/// How many of each thing a 40×40 map has.
const VILLAGERS_PER_TUNING_AREA: usize = 5;
const TREES_PER_TUNING_AREA: usize = 24;
const RABBITS_PER_TUNING_AREA: usize = 6;

/// Nothing is placed closer than this to the map edge.
const EDGE_MARGIN: f32 = 2.0;
/// Minimum distance between villagers, and between a tree and anything else.
const VILLAGER_SPACING: f32 = 2.0;
const TREE_SPACING: f32 = 2.0;
/// Trees keep this far from villagers so the village starts with room to move.
const CLEARING: f32 = 3.0;
/// Rabbits keep this far from tree trunks.
const RABBIT_SPACING: f32 = 1.0;
/// Village radius grows with the number of villagers so they fit at `VILLAGER_SPACING` with
/// room to spare, and is never smaller than the original map's cluster.
const MIN_VILLAGE_RADIUS: f32 = 8.0;
const VILLAGE_AREA_PER_VILLAGER: f32 = VILLAGER_SPACING * VILLAGER_SPACING * 2.5;
/// Initial tree maturities are rolled from this range.
const MATURITY: std::ops::RangeInclusive<f32> = 0.3..=1.0;
/// Random spots tried per placement before giving up on it.
const ATTEMPTS: usize = 200;

fn main() {
    let cli = Cli::parse();
    if cli.size.is_nan() || cli.size <= 0.0 {
        eprintln!("map size must be positive, got {}", cli.size);
        std::process::exit(1);
    }
    let scale = cli.size * cli.size / TUNING_AREA;
    let count = |wanted: Option<usize>, per_tuning_area: usize| {
        wanted.unwrap_or_else(|| (per_tuning_area as f32 * scale).round() as usize)
    };
    let counts = Counts {
        villagers: count(cli.villagers, VILLAGERS_PER_TUNING_AREA),
        trees: count(cli.trees, TREES_PER_TUNING_AREA),
        rabbits: count(cli.rabbits, RABBITS_PER_TUNING_AREA),
    };

    let mut rng = ChaCha8Rng::seed_from_u64(cli.seed);
    let map = generate(&mut rng, cli.size, counts);
    let body = ron::ser::to_string_pretty(&map, PrettyConfig::new().depth_limit(2))
        .expect("map serializes");
    let text = format!(
        "// Generated by `cargo run --bin genmap -- --seed {} --size {}`; regenerate rather than\n\
         // editing by hand. {} villagers in a village at the center, {} trees, {} rabbits.\n{body}\n",
        cli.seed,
        cli.size,
        map.villagers.len(),
        map.trees.len(),
        map.rabbits.len(),
    );
    // Round-trip through the parser so a broken generator can't write a map the game rejects.
    if let Err(err) = MapConfig::from_ron(&text) {
        eprintln!("generated an invalid map: {err}");
        std::process::exit(1);
    }
    if let Err(err) = std::fs::write(&cli.out, text) {
        eprintln!("can't write {}: {err}", cli.out.display());
        std::process::exit(1);
    }
    println!(
        "wrote {}: {}×{}, {} villagers, {} trees, {} rabbits",
        cli.out.display(),
        cli.size,
        cli.size,
        map.villagers.len(),
        map.trees.len(),
        map.rabbits.len(),
    );
}

struct Counts {
    villagers: usize,
    trees: usize,
    rabbits: usize,
}

fn generate(rng: &mut ChaCha8Rng, size: f32, counts: Counts) -> MapConfig {
    let half = size / 2.0 - EDGE_MARGIN;

    // Villagers cluster in a village at the center.
    let village_radius = (counts.villagers as f32 * VILLAGE_AREA_PER_VILLAGER
        / std::f32::consts::PI)
        .sqrt()
        .max(MIN_VILLAGE_RADIUS)
        .min(half);
    let mut villagers: Vec<(f32, f32)> = Vec::with_capacity(counts.villagers);
    for _ in 0..counts.villagers {
        let spot = place(
            rng,
            ATTEMPTS,
            |rng| in_disk(rng, village_radius),
            |spot| clear_of(spot, villagers.iter().copied(), VILLAGER_SPACING),
        );
        villagers.extend(spot);
    }

    // Trees anywhere outside the village clearing, spaced apart.
    let mut trees: Vec<TreeSpec> = Vec::with_capacity(counts.trees);
    for _ in 0..counts.trees {
        let spot = place(
            rng,
            ATTEMPTS,
            |rng| in_square(rng, half),
            |spot| {
                clear_of(spot, villagers.iter().copied(), CLEARING)
                    && clear_of(spot, trees.iter().map(|t| t.pos), TREE_SPACING)
            },
        );
        if let Some(pos) = spot {
            trees.push(TreeSpec {
                pos,
                maturity: round(rng.random_range(MATURITY)),
            });
        }
    }

    // Rabbits anywhere, out of the trunks.
    let mut rabbits: Vec<(f32, f32)> = Vec::with_capacity(counts.rabbits);
    for _ in 0..counts.rabbits {
        let spot = place(
            rng,
            ATTEMPTS,
            |rng| in_square(rng, half),
            |spot| clear_of(spot, trees.iter().map(|t| t.pos), RABBIT_SPACING),
        );
        rabbits.extend(spot);
    }

    MapConfig {
        size,
        texture: None,
        villagers,
        trees,
        rabbits,
    }
}

/// Rolls up to `attempts` spots from `sample` and returns the first that passes `free`.
fn place(
    rng: &mut ChaCha8Rng,
    attempts: usize,
    sample: impl Fn(&mut ChaCha8Rng) -> (f32, f32),
    free: impl Fn((f32, f32)) -> bool,
) -> Option<(f32, f32)> {
    (0..attempts).map(|_| sample(rng)).find(|&spot| free(spot))
}

/// A uniformly random spot in the square of half-side `half`, to a tenth of a unit.
fn in_square(rng: &mut ChaCha8Rng, half: f32) -> (f32, f32) {
    (
        round(rng.random_range(-half..=half)),
        round(rng.random_range(-half..=half)),
    )
}

/// A uniformly random spot in the disk of `radius` around the origin, to a tenth of a unit.
fn in_disk(rng: &mut ChaCha8Rng, radius: f32) -> (f32, f32) {
    let angle = rng.random_range(0.0..std::f32::consts::TAU);
    let r = radius * rng.random_range(0.0f32..=1.0).sqrt();
    (round(r * angle.cos()), round(r * angle.sin()))
}

/// Whether `spot` is at least `distance` from every point in `others`.
fn clear_of(spot: (f32, f32), others: impl IntoIterator<Item = (f32, f32)>, distance: f32) -> bool {
    others.into_iter().all(|(x, z)| {
        let (dx, dz) = (x - spot.0, z - spot.1);
        dx * dx + dz * dz >= distance * distance
    })
}

fn round(value: f32) -> f32 {
    (value * 10.0).round() / 10.0
}
